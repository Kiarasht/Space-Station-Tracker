#!/usr/bin/env python3
"""Check or sync the Android legal resources, and the restartapps.com pages, from the shared app text.

    python3 tools/sync_legal_content.py                 # check Android matches the shared text
    python3 tools/sync_legal_content.py --write         # rewrite the Android resources
    python3 tools/sync_legal_content.py --website ../restartapps.com
                                                        # also write the website's ISS Tracker legal components
"""

import argparse
import html
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]
SHARED = ROOT / "shared/src/commonMain/kotlin/com/restart/spacestationtracker/shared/ui/SharedLegalContent.kt"
ANDROID = ROOT / "app/src/main/res/values/strings.xml"
# (shared constant, Android resource, title, website component)
POLICIES = (
    ("privacyPolicy", "privacy_policy_content", "Privacy Policy", "IssTrackerPrivacy.astro"),
    ("termsOfUse", "terms_of_use_content", "Terms of Use", "IssTrackerTerms.astro"),
)
HEADINGS = {
    "Location", "Local App Data", "Notifications and Calendar", "Advertising and Consent",
    "Purchases", "Analytics and Diagnostics", "Third-Party Data Providers",
    "Retention, Deletion, and Security", "Children", "Your Choices", "Changes and Contact",
    "Contact Us",
}
UPDATED = re.compile(r"^Last Updated: (.+)$")
LINK = re.compile(r"(https://[^\s]+?|[\w.+-]+@[\w-]+\.[\w.]+?)(?=[.,;)]?(?:\s|$))")


def is_heading(paragraph):
    return paragraph in HEADINGS or re.match(r"^\d+\. [^\n]+$", paragraph) is not None


def render_body(title, content):
    blocks = [f"<h2>{html.escape(title)}</h2>"]
    for paragraph in content.split("\n\n"):
        tag = "h3" if is_heading(paragraph) else "p"
        blocks.append(f"<{tag}>{html.escape(paragraph)}</{tag}>")
    return "\n".join(blocks)


def astro_text(text):
    """HTML-escaped text with links, and braces escaped so Astro doesn't read them as expressions."""
    parts = []
    last = 0
    for match in LINK.finditer(text):
        parts.append(html.escape(text[last:match.start()], quote=False))
        target = match.group(1)
        href = target if target.startswith("https://") else f"mailto:{target}"
        parts.append(f'<a href="{html.escape(href)}">{html.escape(target, quote=False)}</a>')
        last = match.end()
    parts.append(html.escape(text[last:], quote=False))
    return "".join(parts).replace("{", "&#123;").replace("}", "&#125;")


def website_component(content):
    """The policy as restartapps.com legal sections. The page shows the date, so the comment carries it."""
    paragraphs = content.split("\n\n")
    updated = UPDATED.match(paragraphs[0])
    if updated is None:
        raise ValueError("Legal text must start with a 'Last Updated:' line")
    sections = [["Overview", []]]
    for paragraph in paragraphs[1:]:
        if is_heading(paragraph):
            sections.append([paragraph, []])
        else:
            sections[-1][1].append(paragraph)
    lines = [
        "---",
        "// Generated by ISS Tracker's tools/sync_legal_content.py from the app's SharedLegalContent.kt. Edit that file instead.",
        f"// Last updated {updated.group(1)}; keep the effective date on the page in step.",
        "---",
        "",
        '<div class="legal-content">',
    ]
    for heading, body in sections:
        if not body:
            continue
        lines.append('  <section class="legal-block" data-reveal>')
        lines.append(f"    <h2>{astro_text(heading)}</h2>")
        lines.extend(f"    <p>{astro_text(paragraph)}</p>" for paragraph in body)
        lines.append("  </section>")
        lines.append("")
    lines[-1] = "</div>"
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true", help="Update the Android resources")
    parser.add_argument("--website", type=Path, help="restartapps.com checkout to write the legal components into")
    args = parser.parse_args()
    shared_source = SHARED.read_text()
    android_source = ANDROID.read_text()
    resources = ET.fromstring(android_source)
    problems = []

    for constant, resource, title, component in POLICIES:
        literal = re.search(rf'const val {constant} = """(.*?)"""', shared_source, re.DOTALL)
        if literal is None:
            raise ValueError(f"Cannot find shared legal content: {constant}")
        body = render_body(title, literal.group(1))
        # AAPT parses backslash escapes even inside CDATA; protect apostrophes.
        android_body = "\n" + "\n".join(
            "        " + line.replace("'", "\\'") for line in body.splitlines()
        ) + "\n    "
        element = resources.find(f"string[@name='{resource}']")
        if element is None:
            raise ValueError(f"Cannot find Android resource: {resource}")
        if (element.text or "").strip() != android_body.strip():
            problems.append(str(ANDROID.relative_to(ROOT)) + ": " + resource)
            if args.write:
                pattern = rf'(<string name="{resource}"[^>]*><!\[CDATA\[).*?(\]\]>\s*</string>)'
                android_source, count = re.subn(
                    pattern, lambda match: match[1] + android_body + match[2],
                    android_source, count=1, flags=re.DOTALL
                )
                if count != 1:
                    raise ValueError(f"Cannot safely replace resource: {resource}")

        if args.website:
            path = args.website / "src/components" / component
            path.write_text(website_component(literal.group(1)))
            print(f"Wrote {path}")

    if args.write:
        ET.fromstring(android_source)
        ANDROID.write_text(android_source)
        print("Synced both Android legal resources.")
        return 0
    if problems:
        print("Legal content is out of sync (run with --write):\n" + "\n".join(problems), file=sys.stderr)
        return 1
    print("Android legal resources match the shared app text.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
